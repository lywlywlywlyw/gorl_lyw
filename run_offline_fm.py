"""Alternating offline training for a latent encoder and Flow-Matching decoder.

The training loop is:

1. Freeze the encoder and fit ``g_phi(s, z)`` to replay-buffer actions with
   conditional flow matching and fresh ``z ~ N(0, I)``.
2. Freeze the decoder, invert buffer actions through its deterministic ODE to
   obtain latent behavior targets, then train:
     * Q(s, a) and V(s) with Implicit Q-Learning (IQL), and
     * pi_theta(z | s) with IQL advantage-weighted behavior cloning.

The IQL update order and losses follow the official implementation:
https://github.com/ikostrikov/implicit_q_learning

``data_path`` may point to a D4RL ``.hdf5`` dataset, an ExORL buffer directory
(or one of its parents) containing ``episode_*.npz`` files, or to a pickle:
  states/observations, actions, rewards,
  next_states/next_observations, dones/terminals or masks.

For legacy GoRL buffers without next states, ``--infer_transitions`` derives
next states by shifting within fixed-length episodes.
"""

